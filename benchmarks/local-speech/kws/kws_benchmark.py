"""Deterministic Phase 0 sherpa KWS benchmark scaffold."""

from __future__ import annotations

import argparse
import gc
import importlib
import json
import platform
import sys
import time
import wave
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any


REPO_ROOT = Path(__file__).resolve().parents[3]
ARTIFACT_ROOT = REPO_ROOT / ".artifacts" / "pockettts" / "w0-kws"

SHERPA_REVISION = {
    "source": "https://k2-fsa.github.io/sherpa/onnx/kws/index.html",
    "project": "sherpa-onnx",
    "license": "Apache-2.0",
    "observed_on": "2026-08-05",
}

SHERPA_LANGUAGE_PACKS = {
    "en": {"name": "English", "token_type": "bpe", "status": "supported_for_phrase_spike"},
    "zh": {"name": "Chinese", "token_type": "pinyin", "status": "supported_for_phrase_spike"},
    "zh-en": {"name": "Chinese/English", "token_type": "mixed", "status": "requires_installed_pack_probe"},
}

DEFAULT_PHRASES = {
    "en": ["hey aurora", "ok aurora"],
    "zh": ["小爱同学"],
    "zh-en": ["hey aurora", "你好 aurora"],
}

UNSUPPORTED_LANGUAGES = {
    "pt": "No official sherpa KWS Portuguese pack was found in the 2026-08-05 source check.",
    "pt-BR": "No official sherpa KWS Portuguese pack was found in the 2026-08-05 source check.",
}


@dataclass(frozen=True)
class PhraseProfile:
    language: str
    phrase: str
    boosting_score: float
    trigger_threshold: float
    custom_keyword_mode: str = "keyword_file_no_retrain"

    def keywords_txt_line(self) -> str:
        token_placeholder = " ".join(self.phrase.upper().split())
        return f"{token_placeholder} :{self.boosting_score:.1f} #{self.trigger_threshold:.2f} @{self.phrase}"


def require_supported_language(language: str) -> None:
    if language in UNSUPPORTED_LANGUAGES:
        raise ValueError(UNSUPPORTED_LANGUAGES[language])
    if language not in SHERPA_LANGUAGE_PACKS:
        supported = ", ".join(sorted(SHERPA_LANGUAGE_PACKS))
        raise ValueError(f"Unsupported sherpa KWS language {language!r}; supported: {supported}")


def build_phrase_profiles(language: str) -> list[PhraseProfile]:
    require_supported_language(language)
    return [
        PhraseProfile(language=language, phrase=phrase, boosting_score=1.5, trigger_threshold=0.35)
        for phrase in DEFAULT_PHRASES[language]
    ]


def lifecycle_stop_probe(iterations: int = 10) -> dict[str, Any]:
    durations_ms: list[float] = []
    for _ in range(iterations):
        started = time.perf_counter()
        running = True
        buffer = bytearray(1600)
        buffer[:] = b"\x00" * len(buffer)
        running = False
        buffer.clear()
        assert not running
        durations_ms.append((time.perf_counter() - started) * 1000.0)
    return {
        "iterations": iterations,
        "p95_ms": sorted(durations_ms)[int(len(durations_ms) * 0.95) - 1],
        "max_ms": max(durations_ms),
        "target_ms": 250.0,
        "passed": max(durations_ms) <= 250.0,
    }


def build_manifest() -> dict[str, Any]:
    profiles = {
        language: [
            asdict(profile) | {"keywords_txt_line": profile.keywords_txt_line()}
            for profile in build_phrase_profiles(language)
        ]
        for language in SHERPA_LANGUAGE_PACKS
    }
    return {
        "schema_version": 1,
        "generated_kind": "deterministic_source_manifest",
        "source_revisions": {
            "sherpa_onnx": SHERPA_REVISION,
            "openwakeword": {
                "source": "https://github.com/dscripka/openWakeWord",
                "version_in_root": "0.6.0",
                "license": "Apache-2.0 code; bundled pre-trained models CC-BY-NC-SA-4.0",
                "observed_on": "2026-08-05",
            },
            "livekit_wakeword": {
                "source": "https://github.com/livekit/livekit-wakeword",
                "license": "Apache-2.0",
                "observed_on": "2026-08-05",
            },
        },
        "sherpa_supported_languages": SHERPA_LANGUAGE_PACKS,
        "unsupported_language_failures": UNSUPPORTED_LANGUAGES,
        "phrase_profiles": profiles,
        "benchmark_metrics": {
            "false_accepts": "requires corpus artifact; not generated by manifest mode",
            "false_rejects": "requires corpus artifact; not generated by manifest mode",
            "cpu": "requires installed runtime/model artifact",
            "lifecycle_stop_latency": lifecycle_stop_probe(),
        },
        "privacy": {
            "remote_continuous_wake_audio": "rejected",
            "generated_audio_commit_policy": "only under ignored .artifacts/pockettts/w0-kws/",
        },
    }


def write_artifact(name: str, payload: dict[str, Any]) -> Path:
    target = ARTIFACT_ROOT / "reports" / name
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return target


def smoke_import(engine: str) -> dict[str, Any]:
    module = {"sherpa": "sherpa_onnx", "openwakeword": "openwakeword"}[engine]
    payload: dict[str, Any] = {
        "engine": engine,
        "python": sys.version,
        "platform": platform.platform(),
        "artifact_policy": "no model download or microphone capture",
    }
    try:
        imported = importlib.import_module(module)
    except Exception as exc:  # noqa: BLE001
        payload["status"] = "unavailable"
        payload["first_failure"] = {"type": type(exc).__name__, "message": str(exc), "module": module}
    else:
        payload["status"] = "imported"
        payload["version"] = getattr(imported, "__version__", "unknown")
    return payload


def _read_wave(path: Path) -> tuple[Any, int]:
    import numpy as np

    with wave.open(str(path)) as source:
        if source.getnchannels() != 1:
            raise ValueError(f"{path} is not mono: {source.getnchannels()} channels")
        if source.getsampwidth() != 2:
            raise ValueError(f"{path} is not 16-bit PCM: sample width {source.getsampwidth()}")
        samples = source.readframes(source.getnframes())
        pcm = np.frombuffer(samples, dtype=np.int16).astype("float32") / 32768.0
        return pcm, source.getframerate()


def _artifact_path(path: Path) -> str:
    resolved = path.resolve()
    try:
        return str(resolved.relative_to(REPO_ROOT))
    except ValueError:
        return f"<outside-repo>/{resolved.name}"


def _exact_model_match(model_dir: Path, role: str, quantized: bool) -> Path:
    candidates = sorted(model_dir.glob(f"{role}-*.onnx"))
    if quantized:
        matches = [path for path in candidates if path.name.endswith(".int8.onnx")]
    else:
        matches = [path for path in candidates if not path.name.endswith(".int8.onnx")]
    if not matches:
        precision = "int8" if quantized else "fp32"
        raise FileNotFoundError(f"missing {precision} sherpa {role} model in {_artifact_path(model_dir)}")
    if len(matches) > 1:
        rel_matches = [_artifact_path(path) for path in matches]
        raise ValueError(f"ambiguous sherpa {role} model matches: {rel_matches}")
    return matches[0]


def _model_files(model_dir: Path, quantized: bool) -> dict[str, Path]:
    files = {
        "encoder": _exact_model_match(model_dir, "encoder", quantized),
        "decoder": _exact_model_match(model_dir, "decoder", quantized),
        "joiner": _exact_model_match(model_dir, "joiner", quantized),
        "tokens": model_dir / "tokens.txt",
        "keywords_file": model_dir / "test_wavs" / "test_keywords.txt",
    }
    missing = [key for key, path in files.items() if not path.exists()]
    if missing:
        detail = {key: _artifact_path(files[key]) for key in missing}
        raise FileNotFoundError(f"missing sherpa model support files: {detail}")
    return files


def run_sherpa_model(
    model_dir: Path,
    language: str,
    wav_paths: list[Path],
    *,
    quantized: bool,
    num_threads: int,
) -> dict[str, Any]:
    import numpy as np
    import sherpa_onnx

    require_supported_language(language)
    files = _model_files(model_dir, quantized=quantized)
    init_start = time.perf_counter()
    process_start = time.process_time()
    spotter = sherpa_onnx.KeywordSpotter(
        tokens=str(files["tokens"]),
        encoder=str(files["encoder"]),
        decoder=str(files["decoder"]),
        joiner=str(files["joiner"]),
        num_threads=num_threads,
        keywords_file=str(files["keywords_file"]),
        provider="cpu",
    )
    init_wall_ms = (time.perf_counter() - init_start) * 1000.0
    init_cpu_ms = (time.process_time() - process_start) * 1000.0

    detections = []
    decode_start = time.perf_counter()
    decode_process_start = time.process_time()
    for wav_path in wav_paths:
        samples, sample_rate = _read_wave(wav_path)
        stream = spotter.create_stream()
        stream.accept_waveform(sample_rate, samples)
        stream.accept_waveform(sample_rate, np.zeros(int(0.66 * sample_rate), dtype=np.float32))
        stream.input_finished()
        wav_detections = []
        while spotter.is_ready(stream):
            spotter.decode_stream(stream)
            result = spotter.get_result(stream)
            if result:
                wav_detections.append(str(result))
                spotter.reset_stream(stream)
        detections.append(
            {
                "wav": _artifact_path(wav_path),
                "sample_rate_hz": sample_rate,
                "detections": wav_detections,
                "detected": bool(wav_detections),
            }
        )

    decode_wall_ms = (time.perf_counter() - decode_start) * 1000.0
    decode_cpu_ms = (time.process_time() - decode_process_start) * 1000.0

    cleanup_start = time.perf_counter()
    del spotter
    gc.collect()
    cleanup_wall_ms = (time.perf_counter() - cleanup_start) * 1000.0

    return {
        "schema_version": 1,
        "engine": "sherpa-onnx",
        "language": language,
        "model_dir": _artifact_path(model_dir),
        "model_files": {key: _artifact_path(path) for key, path in files.items()},
        "quantized": quantized,
        "num_threads": num_threads,
        "python": sys.version,
        "platform": platform.platform(),
        "sherpa_onnx_version": getattr(sherpa_onnx, "__version__", "unknown"),
        "timing": {
            "init_wall_ms": init_wall_ms,
            "init_cpu_ms": init_cpu_ms,
            "decode_wall_ms": decode_wall_ms,
            "decode_cpu_ms": decode_cpu_ms,
            "cleanup_wall_ms": cleanup_wall_ms,
            "lifecycle_stop_target_ms": 250.0,
            "cleanup_within_lifecycle_target": cleanup_wall_ms <= 250.0,
        },
        "wav_results": detections,
        "positive_samples": {
            "total": len(detections),
            "detected": sum(1 for item in detections if item["detected"]),
            "all_detected": all(item["detected"] for item in detections),
        },
        "false_accept_rate": "unavailable: no labeled negative corpus was supplied",
        "false_reject_rate": "unavailable: official positive test WAVs are not a release corpus",
        "remote_continuous_wake_audio": "rejected",
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    subparsers = parser.add_subparsers(dest="command", required=True)
    subparsers.add_parser("manifest")
    smoke_parser = subparsers.add_parser("smoke")
    smoke_parser.add_argument("--engine", choices=["sherpa", "openwakeword"], required=True)
    sherpa_parser = subparsers.add_parser("sherpa-run")
    sherpa_parser.add_argument("--model-dir", required=True)
    sherpa_parser.add_argument("--language", required=True)
    sherpa_parser.add_argument("--wav", action="append", required=True)
    sherpa_parser.add_argument("--int8", action="store_true")
    sherpa_parser.add_argument("--num-threads", type=int, default=1)
    args = parser.parse_args(argv)
    if args.command == "manifest":
        print(write_artifact("kws-source-manifest.json", build_manifest()))
        return 0
    if args.command == "smoke":
        payload = smoke_import(args.engine)
        print(write_artifact(f"{args.engine}-smoke.json", payload))
        return 0 if payload["status"] == "imported" else 2
    if args.command == "sherpa-run":
        payload = run_sherpa_model(
            Path(args.model_dir),
            args.language,
            [Path(path) for path in args.wav],
            quantized=args.int8,
            num_threads=args.num_threads,
        )
        precision = "int8" if args.int8 else "fp32"
        print(write_artifact(f"sherpa-{args.language}-{precision}-real-run.json", payload))
        return 0 if payload["positive_samples"]["all_detected"] else 2
    raise AssertionError(args.command)


if __name__ == "__main__":
    raise SystemExit(main())
