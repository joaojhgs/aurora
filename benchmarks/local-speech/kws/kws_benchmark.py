#!/usr/bin/env python3
"""Deterministic Phase 0 sherpa KWS benchmark scaffold."""

from __future__ import annotations

import argparse
import importlib
import json
import platform
import sys
import time
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any


REPO_ROOT = Path(__file__).resolve().parents[3]
ARTIFACT_ROOT = REPO_ROOT / ".artifacts" / "pockettts" / "w0-kws"

SHERPA_REVISION = {
    "source": "https://k2-fsa.github.io/sherpa/onnx/kws/index.html",
    "project": "sherpa-onnx",
    "license": "Apache-2.0",
    "observed_on": "2026-08-05",
}

SHERPA_LANGUAGE_PACKS = {
    "en": {"name": "English", "token_type": "bpe", "status": "supported_for_phrase_spike"},
    "zh": {"name": "Chinese", "token_type": "pinyin", "status": "supported_for_phrase_spike"},
    "zh-en": {"name": "Chinese/English", "token_type": "mixed", "status": "requires_installed_pack_probe"},
}

DEFAULT_PHRASES = {
    "en": ["hey aurora", "ok aurora"],
    "zh": ["小爱同学"],
    "zh-en": ["hey aurora", "你好 aurora"],
}

UNSUPPORTED_LANGUAGES = {
    "pt": "No official sherpa KWS Portuguese pack was found in the 2026-08-05 source check.",
    "pt-BR": "No official sherpa KWS Portuguese pack was found in the 2026-08-05 source check.",
}


@dataclass(frozen=True)
class PhraseProfile:
    language: str
    phrase: str
    boosting_score: float
    trigger_threshold: float
    custom_keyword_mode: str = "keyword_file_no_retrain"

    def keywords_txt_line(self) -> str:
        token_placeholder = " ".join(self.phrase.upper().split())
        return f"{token_placeholder} :{self.boosting_score:.1f} #{self.trigger_threshold:.2f} @{self.phrase}"


def require_supported_language(language: str) -> None:
    if language in UNSUPPORTED_LANGUAGES:
        raise ValueError(UNSUPPORTED_LANGUAGES[language])
    if language not in SHERPA_LANGUAGE_PACKS:
        supported = ", ".join(sorted(SHERPA_LANGUAGE_PACKS))
        raise ValueError(f"Unsupported sherpa KWS language {language!r}; supported: {supported}")


def build_phrase_profiles(language: str) -> list[PhraseProfile]:
    require_supported_language(language)
    return [
        PhraseProfile(language=language, phrase=phrase, boosting_score=1.5, trigger_threshold=0.35)
        for phrase in DEFAULT_PHRASES[language]
    ]


def lifecycle_stop_probe(iterations: int = 10) -> dict[str, Any]:
    durations_ms: list[float] = []
    for _ in range(iterations):
        started = time.perf_counter()
        running = True
        buffer = bytearray(1600)
        buffer[:] = b"\x00" * len(buffer)
        running = False
        buffer.clear()
        assert not running
        durations_ms.append((time.perf_counter() - started) * 1000.0)
    return {
        "iterations": iterations,
        "p95_ms": sorted(durations_ms)[int(len(durations_ms) * 0.95) - 1],
        "max_ms": max(durations_ms),
        "target_ms": 250.0,
        "passed": max(durations_ms) <= 250.0,
    }


def build_manifest() -> dict[str, Any]:
    profiles = {
        language: [
            asdict(profile) | {"keywords_txt_line": profile.keywords_txt_line()}
            for profile in build_phrase_profiles(language)
        ]
        for language in SHERPA_LANGUAGE_PACKS
    }
    return {
        "schema_version": 1,
        "generated_kind": "deterministic_source_manifest",
        "source_revisions": {
            "sherpa_onnx": SHERPA_REVISION,
            "openwakeword": {
                "source": "https://github.com/dscripka/openWakeWord",
                "version_in_root": "0.6.0",
                "license": "Apache-2.0 code; bundled pre-trained models CC-BY-NC-SA-4.0",
                "observed_on": "2026-08-05",
            },
            "livekit_wakeword": {
                "source": "https://github.com/livekit/livekit-wakeword",
                "license": "Apache-2.0",
                "observed_on": "2026-08-05",
            },
        },
        "sherpa_supported_languages": SHERPA_LANGUAGE_PACKS,
        "unsupported_language_failures": UNSUPPORTED_LANGUAGES,
        "phrase_profiles": profiles,
        "benchmark_metrics": {
            "false_accepts": "requires corpus artifact; not generated by manifest mode",
            "false_rejects": "requires corpus artifact; not generated by manifest mode",
            "cpu": "requires installed runtime/model artifact",
            "lifecycle_stop_latency": lifecycle_stop_probe(),
        },
        "privacy": {
            "remote_continuous_wake_audio": "rejected",
            "generated_audio_commit_policy": "only under ignored .artifacts/pockettts/w0-kws/",
        },
    }


def write_artifact(name: str, payload: dict[str, Any]) -> Path:
    target = ARTIFACT_ROOT / "reports" / name
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return target


def smoke_import(engine: str) -> dict[str, Any]:
    module = {"sherpa": "sherpa_onnx", "openwakeword": "openwakeword"}[engine]
    payload: dict[str, Any] = {
        "engine": engine,
        "python": sys.version,
        "platform": platform.platform(),
        "artifact_policy": "no model download or microphone capture",
    }
    try:
        imported = importlib.import_module(module)
    except Exception as exc:  # noqa: BLE001
        payload["status"] = "unavailable"
        payload["first_failure"] = {"type": type(exc).__name__, "message": str(exc), "module": module}
    else:
        payload["status"] = "imported"
        payload["version"] = getattr(imported, "__version__", "unknown")
    return payload


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    subparsers = parser.add_subparsers(dest="command", required=True)
    subparsers.add_parser("manifest")
    smoke_parser = subparsers.add_parser("smoke")
    smoke_parser.add_argument("--engine", choices=["sherpa", "openwakeword"], required=True)
    args = parser.parse_args(argv)
    if args.command == "manifest":
        print(write_artifact("kws-source-manifest.json", build_manifest()))
        return 0
    if args.command == "smoke":
        payload = smoke_import(args.engine)
        print(write_artifact(f"{args.engine}-smoke.json", payload))
        return 0 if payload["status"] == "imported" else 2
    raise AssertionError(args.command)


if __name__ == "__main__":
    raise SystemExit(main())
