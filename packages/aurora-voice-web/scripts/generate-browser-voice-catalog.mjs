import { createHash } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = dirname(fileURLToPath(import.meta.url))
const packageDir = resolve(scriptDir, '..')
const repoRoot = resolve(packageDir, '..', '..')
const resourcesDir = join(repoRoot, 'rust', 'crates', 'aurora-voice-engine', 'resources')
const ttsPath = join(resourcesDir, 'sherpa_onnx_tts_catalog.json')
const speechPath = join(resourcesDir, 'sherpa_onnx_speech_catalog.json')
const overlayPath = join(repoRoot, 'tools', 'voice-runtime', 'pockettts-packs', 'aurora_pockettts_language_pack_catalog.json')
const outPath = join(packageDir, 'src', 'browser-voice-catalog.generated.ts')
const overlayOutPath = join(packageDir, 'src', 'aurora-pockettts-overlay.generated.ts')
const check = process.argv.includes('--check')

const ttsRaw = readFileSync(ttsPath, 'utf8')
const speechRaw = readFileSync(speechPath, 'utf8')
const overlayRaw = readFileSync(overlayPath, 'utf8')
const tts = JSON.parse(ttsRaw)
const speech = JSON.parse(speechRaw)
const overlay = JSON.parse(overlayRaw)

const generated = `// Generated by scripts/generate-browser-voice-catalog.mjs. Do not edit manually.
import type { AuroraBrowserRawSpeechCatalog, AuroraBrowserRawTtsCatalog } from './browser-voice-catalog.js'

export const AURORA_BROWSER_TTS_CATALOG_RESOURCE_SHA256 = '${sha256(ttsRaw)}'
export const AURORA_BROWSER_SPEECH_CATALOG_RESOURCE_SHA256 = '${sha256(speechRaw)}'

export const AURORA_BROWSER_TTS_CATALOG = ${JSON.stringify(tts, null, 2)} as const satisfies AuroraBrowserRawTtsCatalog

export const AURORA_BROWSER_SPEECH_CATALOG = ${JSON.stringify(speech, null, 2)} as const satisfies AuroraBrowserRawSpeechCatalog
`

const overlayGenerated = `// Generated by scripts/generate-browser-voice-catalog.mjs. Do not edit manually.
import type { AuroraBrowserRawTtsEntry } from './browser-voice-catalog.js'

export const AURORA_BROWSER_POCKETTTS_OVERLAY = ${JSON.stringify(overlay, null, 2)} as const satisfies {
  readonly schema_version: number
  readonly catalog_id: string
  readonly revision: string
  readonly download_base: string
  readonly entries: readonly AuroraBrowserRawTtsEntry[]
}
`

if (check) {
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : ''
  const currentOverlay = existsSync(overlayOutPath) ? readFileSync(overlayOutPath, 'utf8') : ''
  if (current !== generated || currentOverlay !== overlayGenerated) {
    console.error(`browser voice catalog generated sources are stale; run pnpm --filter @aurora/voice-web generate:catalog`)
    process.exit(1)
  }
} else {
  writeFileSync(outPath, generated)
  writeFileSync(overlayOutPath, overlayGenerated)
}

function sha256(value) {
  return createHash('sha256').update(value).digest('hex')
}
