class GenerationError(ValueError):
    """Raised when normalized backend contracts cannot produce safe Rust output."""


def canonical_json(value: Any) -> str:
    """Return Aurora's deterministic JSON representation."""

    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), sort_keys=True)


def sha256_text(value: str) -> str:
    """Return the lowercase SHA-256 digest for UTF-8 text."""

    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def snake_case(value: str) -> str:
    """Convert a generated model name into a stable Rust module name."""

    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", value):
        raise GenerationError(f"unsafe generated model name: {value!r}")
    first = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", value)
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", first).lower()


def rust_type_name(value: str) -> str:
    """Return typify's stable UpperCamelCase spelling for a model name."""

    return "".join(part.capitalize() for part in snake_case(value).split("_"))


def rust_string(value: str) -> str:
    """Render a Python string as a Rust string literal."""

    return json.dumps(value, ensure_ascii=False)


def rust_option(value: str | None) -> str:
    """Render an optional Rust string literal."""

    return "None" if value is None else f"Some({rust_string(value)})"


def rust_slice(values: Iterable[str]) -> str:
    """Render a static Rust string slice."""

    return "&[" + ", ".join(rust_string(value) for value in values) + "]"


def _deduplicated_schemas(contract_schema: Mapping[str, Any]) -> list[dict[str, Any]]:
    by_model: dict[str, dict[str, Any]] = {}
    for raw in contract_schema.get("schemas", []):
        if not isinstance(raw, dict):
            raise GenerationError("contract schemas must be objects")
        model_name = raw.get("model_name")
        schema_hash = raw.get("schema_hash")
        schema = raw.get("schema")
        if not isinstance(model_name, str) or not isinstance(schema_hash, str):
            raise GenerationError("contract schema identity is incomplete")
        if not isinstance(schema, dict):
            raise GenerationError(f"contract schema {model_name} is not an object")
        existing = by_model.get(model_name)
        if existing is not None and existing["schema_hash"] != schema_hash:
            raise GenerationError(f"model {model_name} has conflicting schema hashes")
        by_model.setdefault(model_name, raw)
    return sorted(by_model.values(), key=lambda item: item["model_name"])


def _walk_marker_paths(schema: Any, path: str = "$") -> list[str]:
    paths: list[str] = []
    if isinstance(schema, dict):
        for key, value in schema.items():
            if not key.startswith("x-aurora"):
                continue
            if key not in NORMALIZATION_MARKERS and key not in METADATA_MARKERS:
                raise GenerationError(f"unclassified Aurora schema marker {key!r} at {path}")
            if value is True and key in VECTOR_MARKERS:
                paths.append(f"{path}:{key}")
        for key, value in schema.items():
            if key.startswith("x-aurora"):
                continue
            paths.extend(_walk_marker_paths(value, f"{path}.{key}"))
    elif isinstance(schema, list):
        for index, value in enumerate(schema):
            paths.extend(_walk_marker_paths(value, f"{path}.{index}"))
    return paths


def _model_class(model_name: str) -> Any:
    for module_name in (
        "app.shared.contracts.models.aurora",
        "app.shared.contracts.models.gateway",
        "app.shared.contracts.models.orchestrator",
        "app.shared.contracts.models.stt",
        "app.shared.contracts.models.tts",
        "app.shared.contracts.models.tooling",
    ):
        module = import_module(module_name)
        model = getattr(module, model_name, None)
        if model is not None:
            return model
    raise GenerationError(f"cannot locate Pydantic model for {model_name}")


def _pydantic_normalized(model_name: str, value: Any) -> Any:
    model = _model_class(model_name)
    parsed = model.model_validate(value)
    return parsed.model_dump(mode="json", exclude_none=True)


def _matching_marker_path(marker_paths: list[str], fragment: str, marker: str) -> str:
    matches = [path for path in marker_paths if fragment in path and path.endswith(f":{marker}")]
    if len(matches) != 1:
        raise GenerationError(
            f"expected exactly one marker path for {fragment!r} / {marker}, found {matches}"
        )
    return matches[0]


