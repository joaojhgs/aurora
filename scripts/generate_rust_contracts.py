def _marker_vectors(item: Mapping[str, Any], raw_vectors: Mapping[str, Any]) -> dict[str, Any]:
    schema_id = item["schema_id"]
    marker_paths = _walk_marker_paths(item["schema"])
    if not marker_paths:
        return dict(raw_vectors)
    if schema_id not in _MARKER_POSITIVE_INPUTS and not raw_vectors.get("positive"):
        raise GenerationError(f"missing marker vector fixture for {schema_id}")

    positive_input = (
        raw_vectors.get("positive", {}).get("input")
        if raw_vectors.get("positive")
        else _MARKER_POSITIVE_INPUTS[schema_id]
    )
    positive_normalized = _pydantic_normalized(item["model_name"], positive_input)
    positive_cases = [dict(case) for case in raw_vectors.get("positive_cases", ())]
    negative_cases = [dict(case) for case in raw_vectors.get("negative_cases", ())]
    negative_cases.extend(_marker_negative_cases(schema_id, marker_paths, positive_input))
    model = _model_class(item["model_name"])
    for case in negative_cases:
        if not case.get("marker_paths"):
            continue
        try:
            model.model_validate(case["input"])
        except Exception:
            continue
        raise GenerationError(
            f"marker negative vector unexpectedly accepted for {schema_id}: "
            f"{case['issue_category']}"
        )
    return {
        "positive": {
            "accepted": True,
            "input": positive_input,
            "marker_paths": marker_paths,
            "normalized": positive_normalized,
            "normalized_hash": sha256_text(canonical_json(positive_normalized)),
        },
        "positive_cases": positive_cases,
        "negative_cases": negative_cases,
    }


def _render_models(contract_schema: Mapping[str, Any]) -> tuple[str, dict[str, str]]:
    lines = ["pub mod models {"]
    model_modules: dict[str, str] = {}
    for item in _deduplicated_schemas(contract_schema):
        model_name = item["model_name"]
        module_name = snake_case(model_name)
        rust_name = rust_type_name(model_name)
        model_modules[model_name] = module_name
        lines.extend(
            [
                f"    pub mod {module_name} {{",
                f'        typify::import_types!(schema = "schema/{module_name}.json");',
                "    }",
                f"    pub use {module_name}::{rust_name};",
            ]
        )
    lines.append("}")
    return "\n".join(lines), model_modules


