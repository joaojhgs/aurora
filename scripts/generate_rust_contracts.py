def _rust_const_name(value: str) -> str:
    parts = [part for part in re.split(r"[^A-Za-z0-9]+", value) if part]
    candidate = "_".join(snake_case(part).upper() for part in parts)
    if not candidate or candidate[0].isdigit():
        raise GenerationError(f"cannot render Rust constant name for {value!r}")
    return candidate


def _render_identity_constants(contract_schema: Mapping[str, Any]) -> str:
    lines = ["pub mod ids {"]
    seen: dict[str, str] = {}
    for collection, key in (
        (contract_schema.get("method_descriptors", []), "method_id"),
        (contract_schema.get("event_descriptors", []), "event_topic"),
        (contract_schema.get("envelope_descriptors", []), "envelope_topic"),
    ):
        for item in collection:
            value = item[key]
            name = _rust_const_name(value)
            if existing := seen.get(name):
                raise GenerationError(
                    "duplicate generated Rust identity constant "
                    f"{name} for {existing!r} and {value!r}"
                )
            seen[name] = value
            lines.append(f"    pub const {name}: &str = {rust_string(value)};")
    lines.append("}")
    return "\n".join(lines)


def _render_validator(contract_schema: Mapping[str, Any], model_modules: Mapping[str, str]) -> str:
    arms: list[str] = []
    for item in contract_schema["schemas"]:
        model_name = item["model_name"]
        module_name = model_modules[model_name]
        rust_name = rust_type_name(model_name)
        arms.append(
            f"        {rust_string(item['schema_id'])} => "
            f"serde_json::from_value::<models::{module_name}::{rust_name}>(normalized)"
            ".and_then(serde_json::to_value).map_err(|_| ContractParseError::Decode { "
            "schema_id: schema_id.to_owned() }),"
        )
    arms.append("        _ => Err(ContractParseError::UnknownSchema(schema_id.to_owned())),")
    return "\n".join(
        [
            "pub fn normalize_generated_contract(",
            "    schema_id: &str,",
            "    value: serde_json::Value,",
            ") -> Result<serde_json::Value, ContractParseError> {",
            "    let (normalized, compiled) = normalize_contract_value(schema_id, value)?;",
            "    validate_normalized_contract_schema(schema_id, compiled, &normalized)?;",
            "    match schema_id {",
            *arms,
            "    }",
            "}",
            "",
            "pub fn validate_generated_contract(",
            "    schema_id: &str,",
            "    value: serde_json::Value,",
            ") -> Result<(), ContractParseError> {",
            "    normalize_generated_contract(schema_id, value).map(|_| ())",
            "}",
        ]
    )


